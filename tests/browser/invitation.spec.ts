import { test, expect } from '@playwright/test'

test('invitation, traditions, sound, details, sharing and keyboard dialog', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  // Exercise the real clipboard fallback without opening an OS share sheet in CI.
  await page.addInitScript(() => Object.defineProperty(navigator, 'share', { value: undefined, configurable: true }))
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Open invitation', exact: true }).click()
  await expect(page.locator('.welcome-dialog')).not.toBeVisible()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('The Couple')
  await expect(page.locator('#couple-name-first')).toContainText('Sathvik')
  await expect(page.locator('#couple-name-second')).toContainText('Harika')
  await page.getByRole('button', { name: 'Open the invitation' }).click()
  await expect(page.getByRole('dialog', { name: 'Sathvik & Harika' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('.invitation-dialog')).not.toBeVisible()
  await expect(page.getByRole('button', { name: 'Open the invitation' })).toBeFocused()
  await page.getByRole('tab', { name: 'Talambralu', exact: true }).click()
  await expect(page.getByRole('tabpanel')).toContainText('A little golden rain.')
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('tab', { name: 'Saptapadi', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('button', { name: 'Shower a little joy' }).click()
  await expect(page.getByRole('tab', { name: 'Talambralu', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('button', { name: 'Pause wedding song' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Pause wedding song' }).click()
  await expect(page.getByRole('button', { name: 'Play wedding song' })).toHaveAttribute('aria-pressed', 'false')
  await page.getByText('Planning your journey', { exact: true }).click()
  await expect(page.getByText(/Please wait for the confirmed date and exact venue/)).toBeVisible()
  await expect(page.getByRole('link', { name: 'Explore Shamshabad' })).toHaveAttribute('href', /google.com\/maps\/search/)
  await page.getByRole('button', { name: 'Share our invitation' }).click()
  await expect(page.locator('.toast')).toContainText('Invitation link copied')
  expect(await page.evaluate(() => navigator.clipboard.readText())).toContain('127.0.0.1:5173')
  expect(errors).toEqual([])
})

test('RSVP validates, persists to the API and provides a real receipt', async ({ page }) => {
  await page.goto('/#rsvp')
  await page.getByRole('button', { name: 'Send with love' }).click()
  await expect(page.locator('input[name=name]')).toBeFocused()
  await page.getByLabel('Your name', { exact: true }).fill('Browser QA Guest')
  await page.getByLabel('Email address', { exact: true }).fill('browser-qa@example.invalid')
  await page.getByLabel('Guests, including you').selectOption('3')
  await page.getByLabel('A little note (optional)').fill('Automated local verification record. Remove after testing.')
  await page.getByLabel(/I agree to share/).check()
  const response = page.waitForResponse(response => response.url().endsWith('/api/v1/rsvp') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Send with love' }).click()
  expect((await response).status()).toBe(201)
  await expect(page.locator('#rsvp').getByRole('status')).toContainText('Your reply is safely with us.')
  await expect(page.locator('#rsvp').getByRole('status')).toContainText(/Your reference: [A-F0-9]{16}/)
})

test('failed RSVP keeps form values and allows retry without claiming success', async ({ page }) => {
  await page.route('**/api/v1/rsvp', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"error":"unavailable"}' }))
  await page.goto('/#rsvp')
  await page.getByLabel('Your name', { exact: true }).fill('Retry QA Guest')
  await page.getByLabel('Email address', { exact: true }).fill('retry@example.invalid')
  await page.getByLabel(/I agree to share/).check()
  await page.getByRole('button', { name: 'Send with love' }).click()
  await expect(page.getByRole('alert')).toContainText('could not be saved')
  await expect(page.getByLabel('Your name', { exact: true })).toHaveValue('Retry QA Guest')
})

