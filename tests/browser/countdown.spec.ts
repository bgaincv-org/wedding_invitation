import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test.use({timezoneId:'America/New_York'})
for (const width of [390, 1672]) {
  test(`the second section matches the IST date and fits at ${width}px`, async ({page}) => {
    await page.setViewportSize({width,height:941})
    await page.emulateMedia({reducedMotion:'reduce'})
    await page.clock.setFixedTime(new Date('2026-12-12T11:46:56Z'))
    const errors:string[]=[]
    page.on('pageerror', error=>errors.push(error.message))
    await page.goto('/')
    await page.getByRole('button',{name:'Open invitation',exact:true}).click()
    await expect(page.locator('#hero-title')).toBeFocused()
    await page.getByRole('link',{name:'Scroll to continue'}).click()
    const section=page.locator('#muhurtham')
    await expect(section).toBeInViewport()
    await expect(page.locator('#main section').nth(1)).toHaveAttribute('id','muhurtham')
    await expect(section.locator('.muhurtham-number')).toHaveText(['01','02','03','04'])
    await expect(section.locator('time')).toHaveText('13 December 2026 · 7:20 PM IST')
    await expect(section).toContainText('Date & time to be confirmed')
    await section.locator('img:visible').evaluateAll(images=>Promise.all(images.map(image=>(image as HTMLImageElement).decode())))
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    const scan=await new AxeBuilder({page}).include('#muhurtham').withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()
    expect(scan.violations).toEqual([])
    await page.clock.setFixedTime(new Date('2026-12-12T11:46:57Z'))
    await expect(section.locator('.muhurtham-number')).toHaveText(['01','02','03','03'])
    await page.getByRole('button',{name:'Switch to Telugu'}).click()
    await expect(section.locator('h2')).toHaveText('మా సుముహూర్తానికి')
    await expect(section.locator('dt')).toHaveText(['రోజులు','గంటలు','నిమిషాలు','సెకన్లు'])
    await section.scrollIntoViewIfNeeded()
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    await page.clock.setFixedTime(new Date('2026-12-13T13:50:00Z'))
    await expect(section.locator('.muhurtham-number')).toHaveText(['00','00','00','00'])
    await expect(section.locator('h2')).toHaveText('మా సుముహూర్తం వచ్చింది')
    expect(errors).toEqual([])
  })
}

test('the second section reveals smoothly and shares the decoration controls', async ({page})=>{
  await page.goto('/#muhurtham')
  const section=page.locator('#muhurtham')
  await section.scrollIntoViewIfNeeded()
  await expect(section.locator('.muhurtham-heading')).toHaveCSS('opacity','1')
  const strand=section.locator('.muhurtham-strand').first()
  const first=await strand.getAttribute('style')
  await expect.poll(()=>strand.getAttribute('style')).not.toBe(first)
  await page.getByRole('button',{name:'Pause couple decorations'}).click()
  const paused=await strand.getAttribute('style')
  await page.waitForTimeout(250)
  expect(await strand.getAttribute('style')).toBe(paused)
  await page.getByRole('button',{name:'Resume couple decorations'}).click()
  await section.scrollIntoViewIfNeeded()
  await expect.poll(()=>strand.getAttribute('style')).not.toBe(paused)
  await page.emulateMedia({reducedMotion:'reduce'})
  await expect(strand).toHaveCSS('transform','none')
  await expect(section.locator('.muhurtham-number').first()).toHaveCSS('animation-name','none')
})
