import { test, expect } from '@playwright/test'
import { WELCOME_SESSION_KEY } from '../../src/lib/content'

test.beforeEach(async ({ page }) => { await page.addInitScript(key => sessionStorage.setItem(key, 'yes'), WELCOME_SESSION_KEY) })

test('the toran bends, freezes when paused and adapts to mobile without moving its supports', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Open invitation', exact: true }).click()
  const toran = page.locator('.couple-garland'), canvas = page.locator('.toran-canvas')
  await expect(toran).toHaveAttribute('data-breeze-live', 'true', { timeout: 8000 })
  await expect(page.locator('.couple-person [data-writing-state="complete"]')).toHaveCount(2)
  await page.waitForTimeout(700)
  const supports = await page.locator('.toran-piece').evaluateAll(pieces => pieces.map(piece => piece.getBoundingClientRect().toJSON()))
  const moving = await canvas.screenshot()
  await page.waitForTimeout(450)
  expect(Buffer.compare(moving, await canvas.screenshot())).not.toBe(0)
  expect(await page.locator('.toran-piece').evaluateAll(pieces => pieces.map(piece => piece.getBoundingClientRect().toJSON()))).toEqual(supports)
  await page.getByRole('button', { name: 'Pause couple decorations' }).click()
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  const frozen = await canvas.screenshot()
  await page.waitForTimeout(300)
  expect(Buffer.compare(frozen, await canvas.screenshot())).toBe(0)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(toran).toHaveAttribute('data-breeze-live', 'true')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Resume couple decorations' }).click()
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
  const resumed = await canvas.screenshot()
  await page.waitForTimeout(350)
  expect(Buffer.compare(resumed, await canvas.screenshot())).not.toBe(0)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(canvas).toHaveCSS('opacity', '0')
  await expect(page.locator('.toran-piece img').first()).toHaveCSS('opacity', '1')
})

test('loss and restoration of the toran GPU context preserve readable artwork', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Open invitation', exact: true }).click()
  const toran = page.locator('.couple-garland'), canvas = page.locator('.toran-canvas')
  await expect(toran).toHaveAttribute('data-breeze-live', 'true', { timeout: 8000 })
  await canvas.evaluate(element => { const extension = (element as HTMLCanvasElement).getContext('webgl')!.getExtension('WEBGL_lose_context')!; Object.assign(window, { toranContextTest: extension }); extension.loseContext() })
  await expect(toran).toHaveAttribute('data-breeze-live', 'false')
  await expect(page.locator('.toran-piece img').first()).toHaveCSS('opacity', '1')
  await page.waitForTimeout(150)
  await page.evaluate(() => (window as unknown as { toranContextTest: WEBGL_lose_context }).toranContextTest.restoreContext())
  await expect(toran).toHaveAttribute('data-breeze-live', 'true')
  expect(errors).toEqual([])
})

test('without WebGL the separate toran art stays visible and the invitation still opens', async ({ page }) => {
  await page.addInitScript(() => Object.defineProperty(HTMLCanvasElement.prototype, 'getContext', { value: () => null }))
  await page.goto('/')
  await page.getByRole('button', { name: 'Open invitation', exact: true }).click()
  await expect(page.locator('#hero-title')).toBeFocused({ timeout: 8000 })
  await expect(page.locator('.couple-garland')).toHaveAttribute('data-breeze-live', 'false')
  await expect(page.locator('.toran-piece img').first()).toHaveCSS('opacity', '1')
  await expect(page.locator('.couple-person [data-writing-state="complete"]')).toHaveCount(2)
  const leaf = page.locator('.toran-leaf img').first(), before = await leaf.getAttribute('style')
  await expect.poll(() => leaf.getAttribute('style')).not.toBe(before)
})
